WriteNC <-  function(filename,data.array,var.name,
                     #xlon,ylat,time.index.start=NA, time.index.end=NA, downscale.tseries=NA, downscale.origin=NA,
                     dim.list,
                     prec='double', missval=1.e20,
                     #time.index.start=NA, time.index.end=NA, downscale.tseries=NA, downscale.origin=NA,
                     start.year="undefined",units,calendar='irrelevant',lname=var.name,cfname=var.name, 
                     bounds=FALSE, bnds.list=NA, var.data=NA, 
                     writelist=FALSE, clone_all_vars=FALSE,
                     modulo=NA, modulo.range="", comment=NA,
                     clone_globals=F, clone_all=F, global_clone_file=NA, 
                     clone_exclude=c(),
                     clone_include=c(),
                     verbose=FALSE) {
  #'Creates file filename (netCDF type) with the variable  var.name along with the 
  #'coordinate variables in the netCDF file, CF standard name, long names.
  #'
  #'@param filename: The name under which the data will be written
  #' -----Parameters related to the NetCDF varaible-----
  #'@param data.array: The array containing the values of the variable to 
  #'be written to file. 
  #'@param var.name: The short name of the NetCDF variable being written. In the
  #'current FUDGE driver, picked up from the input var list.
  #'@param units: The units of the NetCDF variable. In the current FUDGE driver, 
  #'obtained by CFChecker
  #'@param lname: The long name of the NetCDF variable being written. In the current 
  #'FUDGE driver, generated by CF.R
  #'@param cfname: The CF-standard-compliant name of the variable being written.
  #'Currently obtained from CF.R, and defaults to var.name.
  #' ------Parameters related to the dimensions of the new NetCDF file----
  #'Note: at present, all time-related coordinates are obtained from the 
  #'time windowing mask file specified as the future predictor, and all 
  #'space-related coordinates are obtained from the spatial mask specified
  #'for the region.
  #'@param dim.list: A list of netCDF dimensions cloned from input files, 
  #'in something close to (x,y,...t) order. Bounds is *not* included
  #'since it has no relevance for the calculations in the main FUDGE
  #'code; the list of dimsnions (and their names) is also used
  #'to clone attributes from the original NetCDf files for the dimsensions, 
  #'such as pressure. The list is also used to determine the dimensionality
  #'of the data to be written to file, if one or more degnerate dimensions
  #'were removed during reading in or manipulating the data. 
  #'Note that this means the parameters xlon, ylat, downscale.tseries, 
  #'downscale.origin and calendar are now depracated and should not
  #'be passed to the FUDGE code.
  #'--Used to create the bounds variables and offsets 
  #'--(neccesary if to be looked at in Ferret)
  #'@param bounds=FALSE: Whether or not to attempt consruction of bounds parameters. 
  #'Defaults to FALSE.
  #'@param bnds.list=NA : The list of bounds values and other parameters to be used
  #'in constructing a variable. Currently cloned from the input mask files; defaults to 
  #'NA if no list is provided. 
  #'
  #'TODO: Check on the missing values for the non-downscaled vars. 
  #'Are they CF-compliant? And if not, how do we deal with the int/double prec. issue?
    
    FUDGEROOT = Sys.getenv(c("FUDGEROOT"))
    #Define variable list and populate it
    var.dat <- list()
    
    #Changed 3-10 to support writing ensemble dimensions
    true.dim <- unlist((lapply(dim.list, "[[", "len")))
    
    if(!clone_all_vars){ #Writes only the vars in the cloned list from input
      if(!writelist){ #Writes a list of vars for the data array
        if(prod(true.dim)==prod(dim(data.array))){
          #If the only difference between the dims stored from the input files
          #and the dimensions of the data array are degenerate dimensions
          dim(data.array) <- true.dim
        }else{
          message(paste("Warning in WriteNC: the data in data.array has dimensions of", 
                        paste(dim(data.array), collapse=" "), 
                        "but the dimensions provided for writing are of the form", 
                        paste(true.dim, collapse=" "), "; all data may not be written to file."))
        }
        var.dat[[var.name]] <- ncvar_def(var.name,units=units,dim.list,missval=missval,longname=lname,prec=prec)#x,y,t1
      }else{ #If data.array *is* a list, assume that it contains several entries with names
        #This is going to have a neat effect on the variable name - add it only if you are 
        if(verbose){message('writing multiple data variables')}
        if(length(units)==1){
          units <- rep(units, length(data.array))
        }
        for (loop in 1:length(data.array)){
          if(prod(true.dim)==prod(dim(data.array[[loop]]))){
            #If the only difference between the dims stored from the input files
            #and the dimensions of the data array are degenerate dimensions
            dim(data.array[[loop]]) <- true.dim
          }else{
            message(paste("Warning in WriteNC: the data in data.array of", loop, "has dimensions of", 
                          paste(dim(data.array), collapse=" "), 
                          "but the dimensions provided for writing are of the form", 
                          paste(true.dim, collapse=" "), "; all data may not be written to file."))
          }
          if(verbose) { message(paste("defining var", var.name[[loop]])) }
          var.dat[[var.name[loop]]] <- ncvar_def(var.name[loop],
                                                 units=as.character(units[loop]), #needed if units are null
                                                 dim.list,
                                                 missval=missval,
                                                 longname=lname[loop],
                                                 prec=prec)#x,y,t1
        }
      }
    }else{
      if(verbose){message('cloning vars bypass')}
    }
       
    #1-5 alternate structure
  #Adding create_dimvar=TRUE 7-13; it doesn't match 
  #the section 8 tools, but is needed to maintain consistency with earlier versions
  #Also making it a double b/c that is what it was in earlier versions as well.
  #and changing the longname to 'bnds'
    bnds <- ncdim_def(name="bnds", longname = 'bnds', units='', vals=as.double(seq(1:2)), create_dimvar=TRUE)
    
    #the variables associated with the dimensions
    for (v in 1:length(var.data)){
      var <- names(var.data)[v]
      if(verbose) { message(paste("defining var", var)) }
      var.dim <- unlist(strsplit(attr(var.data[[v]], "dimids"), ","))
      var.dimlist <- list()
      if(var.dim[1]=='NA'){
        var.dimlist <- NULL
      }else{
        for(d in 1:length(var.dim)){
          #print(var.dim[[d]]) #Blame R's need to return all functions as elements of a list.
          var.dimlist[[d]] <- switch(as.character(var.dim[d]), 
                                     "bnds"=bnds, 
                                     dim.list[[as.character(var.dim[d])]])
        }
      }
      #Check for units attribute in the input data; add if not presnet
      units.tmp <- attr(var.data[[var]], 'units')
      if(is.null(units.tmp)){
        units.tmp <- units[1]
      }
      var.dat[[var]] <- ncvar_def(var, #var.data[[v]], #Don't forget to add the data in somewhere 
                                  units=units.tmp, #Add check for adding units back in if not present
                                  dim=var.dimlist, 
                                  #missval=as.numeric(attr(var.data[[var]], "missval") ), #Commenting this out keeps fillval from being set
                                  longname = attr(var.data[[var]], "longname"), 
                                  prec = attr(var.data[[var]], "prec") #This one gave me hives last time.
                                  )
    }
    #save('var.dat', file="/home/cew/Code/testing/ncvars.out")
    #stop('see if missval is being set here')
    if(verbose) { message("creating nc objects") }
#      save(list=c("var.dat", 'filename'), file="/home/cew/Code/testing/test_out.R")
#      stop("investigate your output")
    nc.obj <- nc_create(filename, var.dat, verbose=FALSE)
    if(verbose) { message("placing nc vars") }
    if(!clone_all_vars){
      if(!writelist){
        nc.obj <- nc_open(filename, write=TRUE)
        ncvar_put(nc.obj, var.dat[[var.name]], data.array)
      }else{
        for (loop in 1:length(data.array)){
          #nc.obj <- nc_open(filename, write=TRUE)
          loop.varname <- names(data.array)[loop]
          if(verbose) { message(paste("populating", loop.varname)) }
          ncvar_put(nc=nc.obj, 
                    varid=var.dat[[loop.varname]], 
                    vals=data.array[[loop.varname]], verbose=FALSE)
        }
      }
    }
    for (v in 1:length(var.data)){
      loop.var <- names(var.data)[[v]]
      if(verbose) { message(paste("adding", loop.var, "and attributes")) }  
      ###This is the code that's giving buggy responses as of 12-16
      ncvar_put(nc.obj, var.dat[[loop.var]], var.data[[loop.var]], verbose=FALSE)
      #Note: failure to include missval as one of the attributes that  doesn't get set 
      #will result in giving all vars a missing value of 1e30. 
      all.att.list <- attributes(var.data[[loop.var]])
      all.att.list <- all.att.list[!(names(all.att.list)%in% c("units", "longname", "prec", "dim", "dimids", "missval"))] #"missval", 
      if(length(all.att.list) > 0){
        for (at in 1:length(all.att.list)){
          ncatt_put(nc.obj, loop.var,  names(all.att.list)[[at]], all.att.list[[at]])
        }
     }
    }
    if(verbose) { print("cloning attributes") }
#message("cloning var values commented out for testing purposes. ADD THIS BACK IN.")
    for (i in 1:length(dim.list)){
      dim.name <- names(dim.list)[i]
      orig.file <- attr(dim.list[[i]], "filename")
#       print(dim.name)
#       print(attributes(dim.list[[i]]))
      if(!is.null(orig.file)){
        orig.nc <- nc_open(orig.file)
        dim.name <- names(dim.list)[i]
        #This may not work if you name the arguments present. Check on that?
        nc.copy.atts(orig.nc, dim.name, nc.obj, dim.name, c("_FillValue", "FillValue", "_missval"))
        nc_close(orig.nc)
      }else{
        if(verbose) { print("null dim; skipping to next") }
      }
      dim.namelist <- c('time', 'lat', 'lon')
      if(dim.name%in%dim.namelist){
        #Link bounds variables to the corresponding dims; link axes
        #Cloning won't do this if you are creating your own time dimension
        dim.axis <- switch(dim.name, 'time' = 'T', 'lat'='Y', 'lon'='X')
        bnds.name <- paste0(dim.name, "_bnds")
        set_att_fun <- function(dim.name, dim.axis, bnds.name, nc.obj){
          ncatt_put(nc.obj, dim.name, 'axis', dim.axis)
          ncatt_put(nc.obj, dim.name, 'bounds', bnds.name)
          return(nc.obj)
        }
        nc.obj <- set_att_fun(dim.name, dim.axis, bnds.name, nc.obj)
      }
    }
    #clone most globals as well
    if(clone_globals){
      #...seriously, why did I include experiment and realizations in this list?
      if(clone_all){
        #prepare to clone all atts from all variables cloned from input
        clone.var.list <- names(var.dat)
      }
      #if(!except){
        global.except.list <- c(c('initialization_method', 'physics_version', 'realization',
                                'product', 
                                'creation_date', 
                                'title', 'forcing', 'source',
                                'parent_experiment_id', 
                                'branch_time', 'modeling_realm', 
                                'table_id', 'tracking_id', 'parent_experiment_rip', 
                                  "Institution", 'Institute_id', 'contact'), 
                                as.vector(clone_exclude))
      #}else{
      #  global.except.list <- NULL
      #}
      if(length(clone_include) > 0){
        global.except.list <- global.except.list[!(global.except.list%in%clone_include)]
      }
      if(length(global_clone_file)==1){
        orig.nc <- nc_open(global_clone_file)
        nc.copy.atts(orig.nc, 0, nc.obj, 0, global.except.list)
        if(clone_all){
          for(v in clone.var.list){
            nc.copy.atts(orig.nc, v, nc.obj, v, c("_FillValue", "FillValue", "_missval", "missing_value", 'units'))
          }
        }
        nc_close(orig.nc)
      }else{
        nc.array <- lapply(global_clone_file, nc_open)
        nc.copy.and.combine.atts(nc.array, 0, nc.obj, 0, global.except.list, 
                                 verbose=FALSE)
        if(clone_all){
          for(v in clone.var.list){
          nc.copy.and.combine.atts(nc.array, v, nc.obj, v, c("_FillValue", "FillValue", "_missval", 'missing_value', 'units'),
                                   verbose=FALSE)
          }
        }
      }
    }
######end commented otu for testing the exceedance code
    if(!is.na(comment[[1]])){
      comment.vars <- names(comment)
      for(var in comment.vars){
        ncatt_put(nc.obj, var, "comment", comment[[var]])
      }
    }
#     #And establish long names in the code
#     ncatt_put(nc.obj,"time","standard_name","time")
#     ncatt_put(nc.obj, "time", "long_name", "time")
#     ncatt_put(nc.obj,"lat","standard_name","latitude")
#     ncatt_put(nc.obj,"lat","long_name","latitude")
#     ncatt_put(nc.obj,"lon","standard_name","longitude")
#     ncatt_put(nc.obj,"lon","long_name","longitude")
    
    ##CEW: figure out how to add these in once rest are tested
#    ncatt_put(nc.obj,var.dat[[var.name]],"units",units)
    #The cfname attribute behavior needs to be checked more
    if(length(cfname)==1 && cfname!='none'){
      ncatt_put(nc.obj,var.dat[[var.name]],"standard_name",cfname)
    }
    #Climatology
    if(!is.na(modulo)){
      ncatt_put(nc.obj, "time", 'modulo', "") #there seems to be no good way to specify that this covers 365 days
      ncatt_put(nc.obj, "time", 'modulo_range', 
                modulo.range, prec="character")
    }
    ########### write grid coordinate bounds ####################
    
    #############################################################  
    nc_close(nc.obj)
    return(filename)
}
